import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { deliverDue } from "../../src/lib/patates/scheduler.mjs";

const directory = mkdtempSync(join(tmpdir(), "patates-test-"));
process.env.PATATES_DB_PATH = join(directory, "test.sqlite");
const { database } = await import("../../src/lib/patates/database.mjs");
let db = database();
const now = Date.now();
db.prepare("INSERT INTO rooms(id,state,expires,due,body) VALUES(?,?,?,?,?)").run("test", "{}", now + 3600000, now - 1000, "test reminder");
db.prepare("INSERT INTO subscriptions(room,device,value) VALUES(?,?,?)").run("test", "device", JSON.stringify({ endpoint: "test" }));
// Reopen the file: reminders survive a process/connection restart.
db.close(); db = new DatabaseSync(process.env.PATATES_DB_PATH);
let delivered = 0;
await deliverDue(db, async () => { delivered++; }, now);
await deliverDue(db, async () => { delivered++; }, now + 31000);
assert.equal(delivered, 1, "a delivered revision is not sent twice");
db.prepare("UPDATE rooms SET revision=revision+1,due=?,notified=0").run(now + 600000);
await deliverDue(db, async () => { delivered++; }, now + 60000);
assert.equal(delivered, 1, "snoozing cancels the old deadline");
db.prepare("UPDATE rooms SET due=NULL,revision=revision+1").run();
await deliverDue(db, async () => { delivered++; }, now + 700000);
assert.equal(delivered, 1, "reset cancels reminders");
db.prepare("UPDATE rooms SET due=?,revision=revision+1").run(now + 701000);
await deliverDue(db, async () => { const e = new Error("gone"); e.statusCode = 410; throw e; }, now + 702000);
assert.equal(db.prepare("SELECT count(*) AS n FROM subscriptions").get().n, 0, "expired subscriptions are removed");
db.prepare("INSERT INTO subscriptions(room,device,value) VALUES(?,?,?)").run("test", "repeat", "{}");
db.prepare("UPDATE rooms SET state=?,due=?,revision=revision+1,notified=0").run(JSON.stringify({ phase: "focus", end: now + 800000 }), now + 770000);
let body = "";
await deliverDue(db, async (_sub, payload) => { body = payload.body; }, now + 770000);
assert.equal(body, "Mola yaklaşıyor. Son yarım dakika.");
assert.equal(db.prepare("SELECT due FROM rooms").get().due, now + 800000, "prewarning schedules the actual deadline");
await deliverDue(db, async () => {}, now + 800000);
assert.equal(db.prepare("SELECT due FROM rooms").get().due, now + 1100000, "overdue focus schedules a five minute reminder");
// Worker restarts six minutes after the end, with an old unprocessed due time.
db.prepare("UPDATE rooms SET due=?,notified=0").run(now + 800000);
let resumed = 0;
await deliverDue(db, async () => { resumed++; }, now + 1160000);
assert.equal(resumed, 0, "restart skips the stale notification");
assert.equal(db.prepare("SELECT due FROM rooms").get().due, now + 1400000, "restart preserves the future ten-minute reminder");
await deliverDue(db, async () => { resumed++; }, now + 1400000);
assert.equal(resumed, 1, "future reminders still deliver after a long restart");
db.prepare("UPDATE rooms SET due=?").run(now + 9000000);
let stale = false;
await deliverDue(db, async () => { stale = true; }, now + 9000000);
assert.equal(stale, false, "retry leases never resurrect a stale session");
db.close(); rmSync(directory, { recursive: true });
console.log("Patates scheduler checks passed: persistence, deduplication, snooze, reset, expired subscriptions");
